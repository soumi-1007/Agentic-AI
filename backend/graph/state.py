from typing import TypedDict, Optional, Any, Dict


class GraphState(TypedDict):
    """Shared workflow state dictionary for LangGraph multi-agent orchestration.

    Fields:
        customer_message (str): The raw customer query input.
        intent (Optional[str]): Classified intent string from Triage Router.
        order_id (Optional[str]): Extracted or validated Order ID (e.g. ORD-1001).
        agent_response (Optional[str]): Natural language response generated by the handling agent.
        formatted_details (Optional[str]): Formatted order details table (if applicable).
        policy_section (Optional[str]): Retrieved policy section header (if applicable).
        handoff_summary (Optional[str]): Human handoff escalation summary string (if applicable).
        escalation_details (Optional[Dict[str, Any]]): Structured human escalation handoff metadata.
        raw_agent_result (Optional[Dict[str, Any]]): Complete result dictionary returned by the handling agent.
    """

    customer_message: str
    intent: Optional[str]
    order_id: Optional[str]
    agent_response: Optional[str]
    formatted_details: Optional[str]
    policy_section: Optional[str]
    handoff_summary: Optional[str]
    escalation_details: Optional[Dict[str, Any]]
    raw_agent_result: Optional[Dict[str, Any]]
